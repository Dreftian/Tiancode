/* ---------- Estado de idioma ---------- */
let lang = readLS(LS_KEYS.lang, 'es');
if (lang !== 'es' && lang !== 'en') lang = 'es';

export function getLang() {
  return lang;
}

export function t(key) {
  return I18N[lang][key];
}

/* Aplica el idioma a todo el DOM y notifica al resto de módulos */
export function applyLang() {
  const rootEl = document.documentElement;
  writeLS(LS_KEYS.lang, lang);
  rootEl.lang = lang;
  document.title = t('page.title');

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t('page.description'));

  // Traduce textos planos
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (t(key) !== undefined) el.textContent = t(key);
  });
  // Traduce atributos aria-label
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    const key = el.getAttribute('data-i18n-aria');
    if (t(key) !== undefined) el.setAttribute('aria-label', t(key));
  });

  // El botón muestra el idioma al que se puede cambiar
  const langToggle = document.getElementById('lang-toggle');
  if (langToggle) langToggle.textContent = lang === 'es' ? 'EN' : 'ES';

  // Router (título según página) y gráficas escuchan este evento
  document.dispatchEvent(new CustomEvent('tiancode:langchange'));
}

export function initI18n() {
  const langToggle = document.getElementById('lang-toggle');
  if (langToggle) {
    langToggle.addEventListener('click', function () {
      lang = lang === 'es' ? 'en' : 'es';
      applyLang();
    });
  }
}
